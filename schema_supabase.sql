-- ==============================================================
-- SCHEMA DO BANCO DE DADOS SUPABASE - CONTROLE DE VENDAS NATURA
-- ==============================================================

-- 1. TABELA DE PRODUTOS
CREATE TABLE IF NOT EXISTS public.produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL,
    descricao TEXT NOT NULL,
    categoria TEXT NOT NULL,
    unidade TEXT DEFAULT 'UN',
    quantidade_comprada INTEGER NOT NULL,
    quantidade_estoque INTEGER NOT NULL,
    quantidade_vendida INTEGER DEFAULT 0,
    vl_unit_sugerido NUMERIC(10,2) NOT NULL,
    desconto_compra_unit NUMERIC(10,2) NOT NULL,
    vl_unit_pago NUMERIC(10,2) NOT NULL,
    desconto_repassado_unit NUMERIC(10,2) DEFAULT 0.0,
    vl_unit_venda_sugerida_final NUMERIC(10,2) NOT NULL,
    preco_revista NUMERIC(10,2) DEFAULT 0.0,
    preco_revista_promo NUMERIC(10,2),
    pagina_revista INTEGER,
    nome_revista TEXT,
    origem TEXT DEFAULT 'Nota Fiscal 05/11/2026',
    observacoes TEXT DEFAULT '',
    data_cadastro TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABELA DE CLIENTES
CREATE TABLE IF NOT EXISTS public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    telefone TEXT,
    email TEXT,
    data_nascimento DATE,
    observacoes TEXT DEFAULT '',
    data_cadastro TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABELA DE VENDAS
CREATE TABLE IF NOT EXISTS public.vendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT REFERENCES public.produtos(id) ON DELETE SET NULL,
    codigo TEXT NOT NULL,
    descricao TEXT NOT NULL,
    quantidade INTEGER NOT NULL,
    vl_unit_pago NUMERIC(10,2) NOT NULL,
    vl_unit_venda NUMERIC(10,2) NOT NULL,
    desconto_repassado_unit NUMERIC(10,2) DEFAULT 0.0,
    vl_total_venda NUMERIC(10,2) NOT NULL,
    lucro_total NUMERIC(10,2) NOT NULL,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE SET NULL,
    cliente TEXT DEFAULT 'Consumidor',
    cliente_telefone TEXT,
    cliente_email TEXT,
    cliente_nascimento DATE,
    forma_pagamento TEXT DEFAULT 'Pix',
    status_pagamento TEXT DEFAULT 'Recebido',
    data_venda DATE NOT NULL,
    observacoes TEXT DEFAULT '',
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Habilitar Políticas de Acesso (RLS) permissivas para uso direto
ALTER TABLE public.produtos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vendas ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Acesso total produtos" ON public.produtos FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso total clientes" ON public.clientes FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso total vendas" ON public.vendas FOR ALL USING (true) WITH CHECK (true);

